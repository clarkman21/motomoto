export const RETRO_CHARS = Object.keys(G).join('');
export const RETRO_CELL = { width: 6, height: 9 };
export const RETRO_PER_ROW = 16;

/** The font sheet: white glyphs with a dark shadow, RETRO_PER_ROW glyphs in each row. */
export function drawRetroFontSheet(shadow = 0x0a0a28) {
  const chars = [...RETRO_CHARS];
  const rows = Math.ceil(chars.length / RETRO_PER_ROW);
  const c = new PixelCanvas(RETRO_PER_ROW * RETRO_CELL.width, rows * RETRO_CELL.height);
  chars.forEach((ch, i) => {
    const ox = (i % RETRO_PER_ROW) * RETRO_CELL.width, oy = Math.floor(i / RETRO_PER_ROW) * RETRO_CELL.height;
    const bits = G[ch].split(' ');
    for (const [dx, dy, col] of [[1, 1, shadow], [0, 0, 0xffffff]]) {
      bits.forEach((row, y) => [...row].forEach((b, x) => b === '1' && c.setPixel(ox + x + dx, oy + y + dy, col)));
    }
  });
  return c;
}

/** Text in capitals with only the characters that the font has (others become a space). */
export function retroText(text) {
  return [...String(text).toUpperCase()].map((ch) => (G[ch] ? ch : ch === '’' ? "'" : ch === '—' ? '-' : ' ')).join('');
}

/** Wrap text to lines of at most n characters (at spaces). */
export function wrapRetro(text, n) {
  const lines = [];
  for (const para of retroText(text).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (line && (line + ' ' + word).length > n) {
        lines.push(line);
        line = word;
      } else line = line ? `${line} ${word}` : word;
    }
    lines.push(line);
  }
  return lines;
}
